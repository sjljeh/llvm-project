        AREA |.data|, DATA, READWRITE
        GBLA COUNT
        DCD COUNT
COUNT   SETA 1
        DCD COUNT
COUNT   SETA COUNT + 2 * 3
        DCD COUNT
COUNT   SETA (COUNT :SHL: 1) :OR: 1
        DCD COUNT

        GBLA SNAPSHOT
SNAPSHOT SETA COUNT
COUNT   SETA 2
        DCD SNAPSHOT, COUNT

        GBLL FLAG
        GBLL COPY
FLAG    SETL {TRUE}
COPY    SETL FLAG
        GBLS LOGICAL
LOGICAL SETS :STR:COPY
        DCB LOGICAL
FLAG    SETL :LNOT:FLAG
LOGICAL SETS :STR:FLAG
        DCB LOGICAL

        GBLS TEXT
TEXT    SETS "AB" :CC: "CD"
        DCB TEXT
TEXT    SETS TEXT :RIGHT: 3
        DCB TEXT
TEXT    SETS (:CHR:0x45) :CC: (TEXT :LEFT: 2)
        DCB TEXT

        GBLS DIRECTIVE
DIRECTIVE SETS "DCB"
        $DIRECTIVE 0x46
        GBLA HEX
HEX     SETA &E
        DCB "$HEX"
        DCB "$FLAG"
        GBLS PREFIX
PREFIX  SETS "DC"
        $PREFIX.B 0x47

        GBLA RESET
RESET   SETA 1
        GBLA RESET
        DCD RESET
BASE    EQU 5
        GBLA FROMEQU
FROMEQU SETA BASE + 1
        DCD FROMEQU
        END

