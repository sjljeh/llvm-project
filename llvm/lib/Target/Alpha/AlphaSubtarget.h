#ifndef LLVM_LIB_TARGET_ALPHA_ALPHASUBTARGET_H
#define LLVM_LIB_TARGET_ALPHA_ALPHASUBTARGET_H

#include "AlphaFrameLowering.h"
#include "AlphaISelLowering.h"
#include "AlphaInstrInfo.h"
#include "AlphaSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "AlphaGenSubtargetInfo.inc"

namespace llvm {
class AlphaTargetMachine;
class LibcallLoweringInfo;

class AlphaSubtarget : public AlphaGenSubtargetInfo {
protected:

  bool HasCT;
  bool IsTASO;

  AlphaInstrInfo InstrInfo;
  AlphaFrameLowering FrameLowering;
  AlphaTargetLowering TLInfo;
  AlphaSelectionDAGInfo TSInfo;

  AlphaSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  ///
  AlphaSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                 const AlphaTargetMachine &TM);
  
  /// ParseSubtargetFeatures - Parses features string setting specified 
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasCT() const { return HasCT; }
  bool isTASO() const { return IsTASO; }

  const AlphaInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const AlphaFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const AlphaRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const AlphaTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const AlphaSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  void initLibcallLoweringInfo(LibcallLoweringInfo &Info) const override;
};
} // End llvm namespace

#endif
